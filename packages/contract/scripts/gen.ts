import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { openApiJson } from '../src/openapi.js';
import { mcpToolListing } from '../src/tools.js';

const root = fileURLToPath(new URL('..', import.meta.url));
const json = openApiJson();
writeFileSync(`${root}openapi.json`, json);
// A TS module carrying the same bytes, so the API can serve openapi.json byte-identical without file I/O.
writeFileSync(
  `${root}src/openapi.generated.ts`,
  `// Generated by \`npm run gen -w @travis/contract\`. Do not edit.\nexport const OPENAPI_JSON: string = ${JSON.stringify(json)};\n`,
);
writeFileSync(`${root}mcp-tools.json`, JSON.stringify(mcpToolListing(), null, 2) + '\n');
console.log(`openapi.json ${json.length} bytes`);
