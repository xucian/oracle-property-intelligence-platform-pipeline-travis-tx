import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { OPENAPI_JSON, mcpToolListing, openApiJson } from '../src/index.js';

const here = (p: string) => fileURLToPath(new URL(`../${p}`, import.meta.url));

describe('openapi.json', () => {
  it('regenerated bytes equal the committed file (run `npm run gen -w @travis/contract`)', () => {
    expect(openApiJson()).toBe(readFileSync(here('openapi.json'), 'utf8'));
  });
  it('the exported module carries the same bytes the API serves', () => {
    expect(OPENAPI_JSON).toBe(readFileSync(here('openapi.json'), 'utf8'));
  });
  it('is OpenAPI 3.1 with servers [{url: "/"}] and every contract route', () => {
    const doc = JSON.parse(openApiJson());
    expect(doc.openapi).toBe('3.1.0');
    expect(doc.servers).toEqual([{ url: '/' }]);
    for (const p of [
      '/v1/meta',
      '/v1/search-centers',
      '/v1/properties/search',
      '/v1/properties/{property_id}',
      '/v1/properties/by-geo-id/{geo_id}',
      '/v1/permits/search',
      '/v1/permits/text-search',
      '/v1/permits/{permit_id}',
      '/v1/contractors/{contractor_attribution_key}',
      '/v1/businesses/search',
      '/v1/businesses/{business_record_id}',
      '/v1/licenses/search',
      '/v1/licenses/{license_record_id}',
      '/v1/runs',
      '/v1/runs/{run_id}/manifest',
      '/v1/agent/chat',
      '/v1/mcp',
      '/v1/openapi.json',
    ]) {
      expect(doc.paths[p], p).toBeDefined();
    }
  });
  it('committed mcp-tools.json equals the generated tool list', () => {
    expect(JSON.stringify(mcpToolListing(), null, 2) + '\n').toBe(
      readFileSync(here('mcp-tools.json'), 'utf8'),
    );
  });
  it('every tool has object input and output schemas and the three annotations', () => {
    const tools = mcpToolListing();
    expect(tools.map((t) => t.name)).toHaveLength(12);
    for (const t of tools) {
      expect(t.inputSchema.type, t.name).toBe('object');
      expect(t.outputSchema.type, t.name).toBe('object');
      expect(t.annotations).toEqual({
        readOnlyHint: true,
        idempotentHint: true,
        openWorldHint: false,
      });
    }
  });
});
